import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Freeze the exact Unicode property semantics used by SC-014-A. Regenerate only
// alongside a reviewed Node/Unicode contract change; --check is deterministic.
export const unicodeVersion = '17.0';
export const scripts = ['Devanagari', 'Bengali', 'Gurmukhi', 'Gujarati', 'Oriya', 'Tamil', 'Telugu', 'Kannada', 'Malayalam', 'Sinhala'];
export const properties = [
  ['visible', '[\\p{L}\\p{N}\\p{P}\\p{S}]', 'u'],
  ['meaningful', '[\\p{L}\\p{N}\\p{Extended_Pictographic}]', 'u'],
  ['ignorable', '\\p{Default_Ignorable_Code_Point}', 'u'],
  ['pictograph', '\\p{Extended_Pictographic}', 'u'],
  ['letter', '\\p{L}', 'u'],
  ['modifier', '\\p{Emoji_Modifier}', 'u'],
  ['control', '[\\p{Cc}\\p{Cs}]', 'u'],
  ['arabic', '[\\p{Script=Arabic}&&\\p{L}]', 'v'],
  ['nonspacing', '\\p{Mn}', 'u'],
  ['ideograph', '\\p{Unified_Ideograph}', 'u'],
  ['common', '[\\p{Script=Inherited}\\p{Script=Common}]', 'u'],
  ...scripts.map(script => [script + 'Letter', `[\\p{L}&&\\p{Script=${script}}]`, 'v']),
  ...scripts.map(script => [script + 'Mark', `[\\p{M}&&\\p{Script=${script}}]`, 'v']),
];
export const propertyRegex = properties.map(([, source, flags]) => new RegExp(source, flags));
export function flagsFor(point) {
  const char = String.fromCodePoint(point);
  return propertyRegex.reduce((mask, pattern, bit) => mask | (pattern.test(char) ? 2 ** bit : 0), 0);
}
export function propertyRanges() {
  if (process.versions.unicode !== unicodeVersion) throw new Error(`Unicode ${unicodeVersion} required, got ${process.versions.unicode}; review the contract before upgrading`);
  const ranges = [];
  for (let point = 0; point <= 0x10ffff; point += 1) {
    const flags = flagsFor(point);
    if (!flags) continue;
    const last = ranges.at(-1);
    if (last && last[1] === point - 1 && last[2] === flags) last[1] = point;
    else ranges.push([point, point, flags]);
  }
  return ranges;
}
export function renderUnicodeClassifier(ranges) {
  const array = column => "'{" + ranges.map(range => range[column]).join(',') + "}'";
  return `-- BEGIN GENERATED UNICODE ${unicodeVersion}\n-- Generated by scripts/sc014-b2-unicode.mjs using SC-014-A Unicode properties.\n-- Bits: ${properties.map(([name], bit) => `${bit}=${name}`).join(', ')}.\ncreate function private.competency_unicode_flags(point integer) returns integer\nlanguage plpgsql immutable strict parallel safe set search_path = '' as $$\ndeclare\n  starts constant integer[] := ${array(0)};\n  ends constant integer[] := ${array(1)};\n  flags constant integer[] := ${array(2)};\n  low integer := 1; high integer := ${ranges.length}; middle integer;\nbegin\n  while low <= high loop\n    middle := (low + high) / 2;\n    if point < starts[middle] then high := middle - 1;\n    elsif point > ends[middle] then low := middle + 1;\n    else return flags[middle]; end if;\n  end loop;\n  return 0;\nend;\n$$;\nrevoke all on function private.competency_unicode_flags(integer) from public;\n-- END GENERATED UNICODE\n`;
}
if (process.argv[1] && fileURLToPath(import.meta.url) === fileURLToPath(new URL('file://' + process.argv[1]))) {
  const target = new URL('../db/isolated/sc014-b2-validation.sql', import.meta.url);
  const original = await readFile(target, 'utf8');
  const rendered = renderUnicodeClassifier(propertyRanges());
  const updated = original.replace(/-- BEGIN GENERATED UNICODE[^]*?-- END GENERATED UNICODE\n/, () => rendered);
  if (updated === original && !original.includes(rendered)) throw new Error('Generated block not found');
  if (process.argv.includes('--check')) {
    if (updated !== original) throw new Error('Unicode SQL snapshot differs; regenerate and review');
    console.log('SC-014-B2 Unicode snapshot matches Node Unicode ' + unicodeVersion);
  } else await writeFile(target, updated);
}
